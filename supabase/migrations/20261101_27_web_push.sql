-- Ta'mir: телефонга push-билдиришнома (Web Push), телефон блокда бўлса ҳам. 5 та илова: мижоз, дўкон, йиғувчи, ҳайдовчи, админ.
-- Нима учун: Telegram хабари келаверади, лекин сайт иловасидан ишлайдиганлар (айниқса мижоз) экранда билдиришнома кўрмасди.
-- Нима ўзгаради:
--   push_subs жадвали: қайси телефон (endpoint ва калитлар) қайси иловага ва кимга обуна бўлган;
--   push_key() — сайтга очиқ VAPID калити (махфий калитни бот ўзи яратади ва app_settings'га ёзади, ҳеч кимга кўрсатилмайди);
--   push_subscribe(...) / push_unsubscribe(...) — иловадаги «🔔 Билдиришнома» тугмаси учун. Ким эканлиги мавжуд сессиялар орқали текширилади;
--   orders_push триггери: мижоз буюртмасининг ҳолати ўзгарса (тўланди, йиғилмоқда, тайёр, йўлда, етказилди, бекор) ботга хабар беради,
--     бот мижознинг телефонига push юборади. Обуна бўлмаган мижоз учун ҳеч нарса қилмайди. Хато бўлса буюртма ўзгариши тўхтамайди.
-- Нима ўзгармайди: orders ва бошқа жадваллар, мавжуд функциялар, Telegram хабарлари.
-- Хавфсизлик: endpoint фақат маълум push хизматлари (Google, Apple, Mozilla, Microsoft) — бот бошқа манзилга сўров юбормайди.
--   Жадвал RLS ёқиқ, сиёсат йўқ: фақат SECURITY DEFINER функциялар ва бот (service role) ўқийди.
-- Орқага қайтариш: 20261101_27_web_push.down.sql
-- Тартиб: 26 дан кейин. SQL Editor'га тўлиқ қўйиб Run.

begin;

create table if not exists public.push_subs (
  id bigint generated by default as identity primary key,
  app text not null check (app in ('shop', 'seller', 'collector', 'driver', 'admin')),
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  lang text not null default 'uz',
  tg_chat_id bigint,          -- ходим ва админ: бот шу Telegram ID'га хабар юборганда push ҳам кетади
  seller_id bigint,           -- дўкон / йиғувчи / ҳайдовчи (sellers.id)
  profile_id bigint,          -- мижоз ёки админ профили
  user_id uuid,               -- мижоз: auth.uid() (orders.user_id)
  created_at timestamptz not null default now(),
  last_ok_at timestamptz,
  unique (endpoint, app)
);
create index if not exists push_subs_chat_idx on public.push_subs (tg_chat_id) where tg_chat_id is not null;
create index if not exists push_subs_user_idx on public.push_subs (user_id) where user_id is not null;
create index if not exists push_subs_profile_idx on public.push_subs (profile_id) where profile_id is not null;
alter table public.push_subs enable row level security;      -- сиёсат йўқ
revoke all on public.push_subs from anon, authenticated;

-- Очиқ калит (сайт обуна бўлиши учун). Бот биринчи ишга тушганда яратади; ҳали бўлмаса null.
CREATE OR REPLACE FUNCTION public.push_key()
 RETURNS text
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select value from public.app_settings where key = 'vapid_public'
$function$;

-- Обуна: p_app — илова, p_token — шу иловадаги сессия (мижоз учун керак эмас: auth.uid()).
CREATE OR REPLACE FUNCTION public.push_subscribe(p_app text, p_token text, p_endpoint text, p_p256dh text, p_auth text, p_lang text DEFAULT 'uz')
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
  s public.sellers; chat bigint; sid bigint; pid bigint; uid uuid; n int;
  h text := encode(digest(coalesce(p_token, ''), 'sha256'), 'hex');
  lg text := case when p_lang = 'ru' then 'ru' else 'uz' end;
begin
  if p_endpoint is null or length(p_endpoint) > 800
     or p_endpoint !~ '^https://(fcm\.googleapis\.com|android\.googleapis\.com|web\.push\.apple\.com|[a-z0-9.-]*push\.services\.mozilla\.com|[a-z0-9.-]*\.notify\.windows\.com)/' then
    raise exception 'bad_endpoint' using errcode = '22023';
  end if;
  if coalesce(p_p256dh, '') !~ '^[A-Za-z0-9_-]{80,100}={0,2}$' or coalesce(p_auth, '') !~ '^[A-Za-z0-9_-]{16,32}={0,2}$' then
    raise exception 'bad_keys' using errcode = '22023';
  end if;

  if p_app = 'shop' then
    uid := auth.uid();
    if uid is null then raise exception 'no_session'; end if;
    pid := public.my_profile_id();
  elsif p_app = 'driver' then
    s := public.drv_auth(p_token);
    chat := s.tg_chat_id; sid := s.id;
  elsif p_app in ('collector', 'seller') then
    select x.* into s from public.collector_sessions ss join public.sellers x on x.id = ss.seller_id
     where ss.token_hash = h and ss.expires_at > now() and x.role = p_app and x.status = 'active';
    if not found then raise exception 'not_authorized'; end if;
    chat := s.tg_chat_id; sid := s.id;
  elsif p_app = 'admin' then
    perform public.admin_check(p_token);
    pid := public.my_profile_id();
    chat := (select tg_id from public.profiles where id = pid);
  else
    raise exception 'bad_app' using errcode = '22023';
  end if;

  insert into public.push_subs (app, endpoint, p256dh, auth, lang, tg_chat_id, seller_id, profile_id, user_id)
  values (p_app, p_endpoint, p_p256dh, p_auth, lg, chat, sid, pid, uid)
  on conflict (endpoint, app) do update set p256dh = excluded.p256dh, auth = excluded.auth, lang = excluded.lang,
    tg_chat_id = excluded.tg_chat_id, seller_id = excluded.seller_id, profile_id = excluded.profile_id, user_id = excluded.user_id, created_at = now();

  -- бир киши учун кўпи билан 10 та телефон/браузер: эскилари ўчади
  select count(*) into n from public.push_subs where app = p_app
    and ((chat is not null and tg_chat_id = chat) or (uid is not null and user_id = uid));
  if n > 10 then
    delete from public.push_subs where id in (
      select id from public.push_subs where app = p_app and ((chat is not null and tg_chat_id = chat) or (uid is not null and user_id = uid))
       order by created_at desc offset 10);
  end if;
  return true;
end $function$;

-- Билдиришномани ўчириш (шу телефондаги шу илова учун). Endpoint'ни фақат шу телефон билади.
CREATE OR REPLACE FUNCTION public.push_unsubscribe(p_app text, p_endpoint text)
 RETURNS boolean
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  with d as (delete from public.push_subs where app = p_app and endpoint = p_endpoint returning 1) select exists (select 1 from d)
$function$;

-- Мижоз буюртмаси ҳолати ўзгарса → бот push юборади (фақат обуна бўлганлар учун).
CREATE OR REPLACE FUNCTION public.orders_push_notify()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare st text;
begin
  st := case
    when new.cancelled_at is not null and old.cancelled_at is null then 'cancelled'
    when new.stage is distinct from old.stage and new.stage = 1 then 'collecting'
    when new.stage is distinct from old.stage and new.stage = 2 then 'ready'
    when new.stage is distinct from old.stage and new.stage = 3 then 'on_way'
    when new.stage is distinct from old.stage and new.stage = 4 then 'delivered'
    when new.pay_status = 'paid' and old.pay_status is distinct from 'paid' then 'paid'
  end;
  if st is null then return new; end if;
  if not exists (select 1 from public.push_subs where app = 'shop'
                  and (user_id = new.user_id or (new.profile_id is not null and profile_id = new.profile_id))) then
    return new;
  end if;
  begin
    perform public.bot_post(jsonb_build_object('push_order', new.no, 'st', st));
  exception when others then
    raise warning 'orders_push_notify: %', sqlerrm;      -- push бўлмаса ҳам буюртма ўзгариши тўхтамайди
  end;
  return new;
end $function$;

drop trigger if exists orders_push on public.orders;
create trigger orders_push after update of stage, pay_status, cancelled_at on public.orders
  for each row execute function public.orders_push_notify();

revoke all on function public.push_key(), public.push_subscribe(text, text, text, text, text, text), public.push_unsubscribe(text, text) from public;
grant execute on function public.push_key(), public.push_subscribe(text, text, text, text, text, text), public.push_unsubscribe(text, text) to anon, authenticated, service_role;
revoke all on function public.orders_push_notify() from public, anon, authenticated;

commit;

