-- Ta'mir: буюртма ҳолатлари журнали (order_events). TZ 1-босқич, ADR-002 (В вариант).
-- Нима ўзгаради:
--   order_events жадвали: буюртмада stage, pay_status, picker_id, driver_id, received_at, received_ok, cancelled_at ўзгарса, ким ва қачон ёзилади (фақат қўшилади);
--   orders даги триггер шуни ўзи ёзади (ҳеч бир эски код ўзгармайди);
--   order_status(буюртма) — ҳисобланган ном (yangi, tolandi, yigilmoqda, parkda, yolda, yetkazildi, yopildi, bekor);
--   admin_order_events(код, №) — админга буюртма тарихи.
-- «Ким»: админ — admin:ID; йиғувчи/ҳайдовчи тайинланса — collector:ID / driver:ID; set_config('tamir.actor') берилса шу; қолгани system.
-- Нима ўзгармайди: orders ва бошқа жадваллар, мавжуд функциялар. Эски буюртмалар учун тарих йўқ (бошланиш белгиси ёзилади).
