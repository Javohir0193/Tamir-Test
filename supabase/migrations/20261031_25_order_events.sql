begin;

create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_no bigint not null,
  field text not null,
  old_value text,
  new_value text,
  actor text not null default 'system',
  at timestamptz not null default now()
);
create index if not exists order_events_order_idx on public.order_events (order_no, id);
alter table public.order_events enable row level security;      -- сиёсат йўқ: фақат SECURITY DEFINER функциялар ўқийди/ёзади
revoke all on public.order_events from anon, authenticated;

CREATE OR REPLACE FUNCTION public.order_events_log()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare a text; adm text := nullif(current_setting('app.admin_id', true), '');
begin
  a := coalesce(nullif(current_setting('tamir.actor', true), ''), case when adm is not null then 'admin:' || adm end, 'system');
  if tg_op = 'INSERT' then
    insert into public.order_events (order_no, field, new_value, actor) values (new.no, 'created', new.mode, case when auth.uid() is not null then 'customer' else a end);
    return new;
  end if;
  if new.stage is distinct from old.stage then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'stage', old.stage::text, new.stage::text, a); end if;
  if new.pay_status is distinct from old.pay_status then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'pay_status', old.pay_status, new.pay_status, a); end if;
  if new.picker_id is distinct from old.picker_id then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'picker_id', old.picker_id::text, new.picker_id::text, coalesce(case when adm is not null then a end, 'collector:' || new.picker_id)); end if;
  if new.driver_id is distinct from old.driver_id then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'driver_id', old.driver_id::text, new.driver_id::text, coalesce(case when adm is not null then a end, 'driver:' || new.driver_id)); end if;
  if new.received_ok is distinct from old.received_ok then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'received_ok', old.received_ok::text, new.received_ok::text, case when adm is null and a = 'system' then 'customer' else a end); end if;
  if new.received_at is distinct from old.received_at then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'received_at', old.received_at::text, new.received_at::text, case when adm is null and a = 'system' then 'customer' else a end); end if;
  if new.cancelled_at is distinct from old.cancelled_at then insert into public.order_events (order_no, field, old_value, new_value, actor) values (new.no, 'cancelled_at', old.cancelled_at::text, new.cancelled_at::text, a); end if;
  return new;
end $function$;

drop trigger if exists orders_events on public.orders;
create trigger orders_events after insert or update on public.orders for each row execute function public.order_events_log();

CREATE OR REPLACE FUNCTION public.order_status(o public.orders)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  select case
    when o.cancelled_at is not null then 'cancelled'
    when o.stage = 0 and o.pay_status <> 'paid' and o.pay_status <> 'none' then 'new'
    when o.stage = 0 then 'paid'
    when o.stage = 1 and coalesce(o.picked, 0) = 0 then 'assigned'
    when o.stage = 1 then 'collecting'
    when o.stage = 2 then 'at_park'
    when o.stage = 3 then 'on_way'
    when o.stage >= 4 and o.received_at is null then 'delivered'
    else 'closed' end
$function$;

CREATE OR REPLACE FUNCTION public.admin_order_events(p_code text, p_no bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  perform public.admin_check(p_code);
  return coalesce((select jsonb_agg(jsonb_build_object('at', e.at, 'field', e.field, 'old', e.old_value, 'new', e.new_value, 'actor', e.actor,
           'who', case when e.actor like 'admin:%' then coalesce((select a.name from public.admin_users a where a.id = nullif(split_part(e.actor, ':', 2), '')::bigint), e.actor)
                       when e.actor like 'collector:%' or e.actor like 'driver:%' then coalesce((select s.name from public.sellers s where s.id = nullif(split_part(e.actor, ':', 2), '')::bigint), e.actor)
                       else e.actor end) order by e.id)
           from public.order_events e where e.order_no = p_no), '[]'::jsonb);
end $function$;

revoke all on function public.order_events_log() from public, anon, authenticated;
revoke all on function public.admin_order_events(text, bigint) from public, anon;
grant execute on function public.admin_order_events(text, bigint) to authenticated;
grant execute on function public.order_status(public.orders) to authenticated, service_role;

commit;
