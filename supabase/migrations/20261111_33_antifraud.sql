-- Ta'mir: оддий антифрод — шубҳали буюртма ва аккаунтларни белгилаш, админ кўриб қарор қилади (ADR-014).
-- Нима учун: ҳозир кўп буюртма бериб тўламаслик, бир телефонни бир нечта аккаунтда ишлатиш, тез-тез «товар келмади»
--   шикояти ёки баҳоларни сунъий кўтаришни ҳеч ким кўрмайди. Админ «blacklist» белгиси қўйса ҳам, у буюртма беришни тўхтатмас эди.
-- Нима ўзгаради (фақат қўшилади):
--   fraud_flags жадвали: битта белги = битта қоида × объект (key ноёб, қайта белгиланмайди), очко (score), тафсилот, қарор.
--   fraud_scan(): қоидалар (чегаралар app_settings'да, админ ўзгартира олади):
--     velocity   — профил 1 соатда ≥ fraud_orders_hour (5) буюртма;
--     unpaid     — профил 24 соатда ≥ fraud_unpaid_day (3) тўланмаган/муддати ўтган буюртма;
--     phone      — бир телефон 30 кунда ≥ fraud_phone_profiles (3) хил профил буюртмасида;
--     complain   — профил 30 кунда ≥ fraud_complaints (3) марта «олмадим/муаммо» (received_ok = false);
--     bigfirst   — профилнинг биринчи буюртмаси ≥ fraud_big_first (20 000 000 сўм) ва тўланмаган;
--     devices    — профилга 24 соатда ≥ fraud_devices_day (5) янги қурилма уланган;
--     review_burst — дўконга 24 соатда ≥ fraud_reviews_day (5) баҳо (сунъий кўтариш шубҳаси).
--   Янги белги → admin_alerts га эмас, Telegram'да админларга «🕵️ Антифрод» хабари (бир марта).
--   pg_cron: ҳар 10 дақиқада fraud_scan() (cron бўлмаса — admin_fraud очилганда ҳам ишлайди).
--   Админ: admin_fraud(code, status), admin_fraud_decide(code, id, 'ok'|'fraud', note, block) — ҳуқуқ 'people', аудит журнали.
--     'fraud' + block → профилга 'blacklist' белгиси ва сабаб (admin_customer_set билан бир хил майдонлар).
--   'blacklist' профил энди янги буюртма бера олмайди ва баҳо ёза олмайди (orders/reviews'да BEFORE INSERT триггер, account_blocked).
-- Автоматик блоклаш ЙЎҚ: тизим фақат белгилайди, қарорни админ қилади.
-- Нима ўзгармайди: create_order, тўлов функциялари, мавжуд жадваллар ва API имзолари.
-- Орқага қайтариш: 20261111_33_antifraud.down.sql (белгилар ўчади, blacklist белгилари профилда қолади).
-- Тартиб: 32 дан кейин (reviews жадвали керак), аввал test базада. SQL Editor'га тўлиқ қўйиб Run.

begin;

create table if not exists public.fraud_flags (
  id          bigint generated by default as identity primary key,
  key         text not null unique,
  rule        text not null,
  score       int  not null default 10 check (score between 0 and 100),
  profile_id  bigint references public.profiles(id) on delete cascade,
  order_no    bigint references public.orders(no) on delete cascade,
  seller_id   bigint references public.sellers(id) on delete cascade,
  text        text not null,
  details     jsonb not null default '{}'::jsonb,
  status      text not null default 'open' check (status in ('open', 'ok', 'fraud')),
  note        text,
  decided_by  text,
  decided_at  timestamptz,
  created_at  timestamptz not null default now()
);
create index if not exists fraud_flags_open_idx on public.fraud_flags (created_at desc) where status = 'open';
create index if not exists fraud_flags_profile_idx on public.fraud_flags (profile_id);
alter table public.fraud_flags enable row level security;
revoke all on table public.fraud_flags from public, anon, authenticated;

-- сканер учун индекслар (буюртма вақти бўйича профил)
create index if not exists orders_profile_created_idx on public.orders (profile_id, created_at desc) where profile_id is not null;

insert into public.app_settings (key, value)
select k, v from (values ('fraud_orders_hour', '5'), ('fraud_unpaid_day', '3'), ('fraud_phone_profiles', '3'), ('fraud_complaints', '3'),
                         ('fraud_big_first', '20000000'), ('fraud_devices_day', '5'), ('fraud_reviews_day', '5')) x(k, v)
 where not exists (select 1 from public.app_settings a where a.key = x.k);

CREATE OR REPLACE FUNCTION public.fraud_setting(p_key text, p_def integer)
 RETURNS integer
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select coalesce((select nullif(value, '')::int from public.app_settings where key = p_key and value ~ '^\d+$'), p_def)
$function$;

CREATE OR REPLACE FUNCTION public.fraud_scan()
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r record; n int := 0;
        oh int := public.fraud_setting('fraud_orders_hour', 5);    ud int := public.fraud_setting('fraud_unpaid_day', 3);
        pp int := public.fraud_setting('fraud_phone_profiles', 3); cm int := public.fraud_setting('fraud_complaints', 3);
        bf int := public.fraud_setting('fraud_big_first', 20000000); dv int := public.fraud_setting('fraud_devices_day', 5);
        rd int := public.fraud_setting('fraud_reviews_day', 5);
        nm text;
begin
  for r in
    insert into public.fraud_flags (key, rule, score, profile_id, order_no, seller_id, text, details)
    select w.key, w.rule, w.score, w.profile_id, w.order_no, w.seller_id, w.text, w.details from (
      -- 1) кўп буюртма: соатлик ойна (бир соатда бир марта белгиланади)
      select 'velocity:' || o.profile_id || ':' || to_char(date_trunc('hour', now()), 'YYYYMMDDHH24') key, 'velocity' rule, 30 score,
             o.profile_id, null::bigint order_no, null::bigint seller_id,
             'Профил #' || o.profile_id || ': 1 соатда ' || count(*) || ' та буюртма' text, jsonb_build_object('orders', count(*), 'limit', oh) details
        from public.orders o where o.profile_id is not null and o.created_at > now() - interval '1 hour'
       group by o.profile_id having count(*) >= oh
      union all
      -- 2) тўланмаган буюртмалар (кунига бир марта)
      select 'unpaid:' || o.profile_id || ':' || to_char(now(), 'YYYYMMDD'), 'unpaid', 30, o.profile_id, null, null,
             'Профил #' || o.profile_id || ': 24 соатда ' || count(*) || ' та тўланмаган буюртма', jsonb_build_object('orders', count(*), 'limit', ud)
        from public.orders o where o.profile_id is not null and o.created_at > now() - interval '24 hours'
         and (o.pay_status = 'expired' or (o.pay_status = 'unpaid' and o.pay_due < now()))
       group by o.profile_id having count(*) >= ud
      union all
      -- 3) бир телефон бир нечта профилда
      select 'phone:' || x.ph, 'phone', 40, null, null, null,
             'Телефон ' || x.ph || ' — ' || x.c || ' та ҳар хил профилда', jsonb_build_object('profiles', x.ids, 'limit', pp)
        from (select right(regexp_replace(o.phone, '\D', '', 'g'), 9) ph, count(distinct o.profile_id) c, jsonb_agg(distinct o.profile_id) ids
                from public.orders o where o.profile_id is not null and o.created_at > now() - interval '30 days'
                 and length(regexp_replace(o.phone, '\D', '', 'g')) >= 9
               group by 1 having count(distinct o.profile_id) >= pp) x
      union all
      -- 4) тез-тез шикоят (ойига бир марта)
      select 'complain:' || o.profile_id || ':' || to_char(now(), 'YYYYMM'), 'complain', 40, o.profile_id, null, null,
             'Профил #' || o.profile_id || ': 30 кунда ' || count(*) || ' марта «олмадим/муаммо»', jsonb_build_object('orders', jsonb_agg(o.no), 'limit', cm)
        from public.orders o where o.profile_id is not null and o.received_ok = false and o.received_at > now() - interval '30 days'
       group by o.profile_id having count(*) >= cm
      union all
      -- 5) катта биринчи буюртма, тўланмаган
      select 'bigfirst:' || o.no, 'bigfirst', 20, o.profile_id, o.no, null,
             '№' || o.no || ': профилнинг биринчи буюртмаси ' || o.total || ' сўм, тўланмаган', jsonb_build_object('total', o.total, 'limit', bf)
        from public.orders o where o.profile_id is not null and o.created_at > now() - interval '3 days' and o.total >= bf
         and o.pay_status not in ('paid', 'refunded') and o.cancelled_at is null
         and not exists (select 1 from public.orders p where p.profile_id = o.profile_id and p.no < o.no)
      union all
      -- 6) кўп янги қурилма (кунига бир марта)
      select 'devices:' || d.profile_id || ':' || to_char(now(), 'YYYYMMDD'), 'devices', 20, d.profile_id, null, null,
             'Профил #' || d.profile_id || ': 24 соатда ' || count(*) || ' та янги қурилма', jsonb_build_object('devices', count(*), 'limit', dv)
        from public.profile_devices d where d.created_at > now() - interval '24 hours'
       group by d.profile_id having count(*) >= dv
      union all
      -- 7) дўконга бир кунда кўп баҳо
      select 'review_burst:' || v.seller_id || ':' || to_char(now(), 'YYYYMMDD'), 'review_burst', 30, null, null, v.seller_id,
             'Дўкон #' || v.seller_id || ': 24 соатда ' || count(*) || ' та баҳо (ўртача ' || round(avg(v.rating), 1) || ')',
             jsonb_build_object('reviews', count(*), 'profiles', count(distinct v.profile_id), 'limit', rd)
        from public.reviews v where v.seller_id is not null and v.created_at > now() - interval '24 hours'
       group by v.seller_id having count(*) >= rd
    ) w
    on conflict (key) do nothing
    returning text, profile_id
  loop
    n := n + 1;
    select name into nm from public.profiles where id = r.profile_id;
    perform public.bot_post(jsonb_build_object('alert', '🕵️ Антифрод: ' || r.text || coalesce(' (' || nm || ')', '') || E'\nАдмин панель → «Антифрод»'));
  end loop;
  return n;
end $function$;

-- рўйхат (админ): очиқ белгилар биринчи, профил ва телефон билан
CREATE OR REPLACE FUNCTION public.admin_fraud(p_code text, p_status text DEFAULT 'open'::text, p_limit integer DEFAULT 200)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare ph boolean;
begin
  perform public.admin_check(p_code); perform public.admin_need('people');
  ph := public.admin_can('phones');
  perform public.fraud_scan();
  return jsonb_build_object(
    'open', (select count(*) from public.fraud_flags where status = 'open'),
    'items', coalesce((select jsonb_agg(jsonb_build_object('id', f.id, 'rule', f.rule, 'score', f.score, 'text', f.text, 'details', f.details,
               'status', f.status, 'note', f.note, 'by', f.decided_by, 'at', f.created_at, 'no', f.order_no, 'seller', f.seller_id,
               'profile', case when p.id is null then null else jsonb_build_object('id', p.id, 'name', p.name,
                          'phone', case when ph then p.phone else left(coalesce(p.phone, ''), 5) || '…' end,
                          'blocked', 'blacklist' = any(p.tags), 'orders', (select count(*) from public.orders o where o.profile_id = p.id)) end)
             order by (f.status = 'open') desc, f.id desc)
       from (select * from public.fraud_flags where nullif(p_status, '') is null or status = p_status
              order by id desc limit least(greatest(coalesce(p_limit, 200), 1), 500)) f
       left join public.profiles p on p.id = f.profile_id), '[]'::jsonb));
end $function$;

-- қарор (ядро): 'ok' — шубҳа асоссиз, 'fraud' — фирибгар; p_block → профилга blacklist
CREATE OR REPLACE FUNCTION public.fraud_decide(p_id bigint, p_decision text, p_note text, p_block boolean, p_by text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare f public.fraud_flags; why text := nullif(btrim(coalesce(p_note, '')), ''); blocked boolean := false;
begin
  if p_decision not in ('ok', 'fraud') then raise exception 'bad_value'; end if;
  if p_decision = 'fraud' and length(coalesce(why, '')) < 3 then raise exception 'reason_required'; end if;
  select * into f from public.fraud_flags where id = p_id for update;
  if not found then raise exception 'unknown_key'; end if;
  if f.status <> 'open' then raise exception 'already_decided'; end if;
  update public.fraud_flags set status = p_decision, note = left(why, 300), decided_by = left(coalesce(p_by, 'admin'), 60), decided_at = now() where id = p_id;
  if p_decision = 'fraud' and coalesce(p_block, false) and f.profile_id is not null then
    update public.profiles set tags = array(select distinct t from unnest(tags || array['blacklist']) t), block_reason = left('Антифрод: ' || why, 300)
     where id = f.profile_id;
    blocked := true;
  end if;
  perform public.admin_log('fraud_' || p_decision, 'fraud_flag', p_id::text, jsonb_build_object('rule', f.rule, 'key', f.key),
                           jsonb_build_object('profile', f.profile_id, 'blocked', blocked), why);
  return jsonb_build_object('ok', true, 'blocked', blocked);
end $function$;

CREATE OR REPLACE FUNCTION public.admin_fraud_decide(p_code text, p_id bigint, p_decision text, p_note text DEFAULT NULL::text, p_block boolean DEFAULT false)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  perform public.admin_check(p_code); perform public.admin_need('people');
  return public.fraud_decide(p_id, p_decision, p_note, p_block, 'admin:' || coalesce(current_setting('app.admin_name', true), ''));
end $function$;

-- blacklist профил янги буюртма бера олмайди ва баҳо ёза олмайди
CREATE OR REPLACE FUNCTION public.profile_not_blocked()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.profile_id is not null and exists (select 1 from public.profiles where id = new.profile_id and 'blacklist' = any(tags)) then
    raise exception 'account_blocked' using errcode = '42501';
  end if;
  return new;
end $function$;

drop trigger if exists orders_not_blocked on public.orders;
create trigger orders_not_blocked before insert on public.orders for each row execute function public.profile_not_blocked();
drop trigger if exists reviews_not_blocked on public.reviews;
create trigger reviews_not_blocked before insert on public.reviews for each row execute function public.profile_not_blocked();

revoke all on function public.fraud_setting(text, integer) from public, anon, authenticated;
revoke all on function public.fraud_scan() from public, anon, authenticated;
revoke all on function public.fraud_decide(bigint, text, text, boolean, text) from public, anon, authenticated;
revoke all on function public.profile_not_blocked() from public, anon, authenticated;
revoke all on function public.admin_fraud(text, text, integer) from public, anon;
revoke all on function public.admin_fraud_decide(text, bigint, text, text, boolean) from public, anon;
grant execute on function public.admin_fraud(text, text, integer), public.admin_fraud_decide(text, bigint, text, text, boolean) to authenticated;
grant execute on function public.fraud_scan(), public.fraud_decide(bigint, text, text, boolean, text) to service_role;

do $$ begin
  if exists (select 1 from pg_namespace where nspname = 'cron') then
    perform cron.schedule('tamir-fraud-scan', '*/10 * * * *', 'select public.fraud_scan()');
  end if;
end $$;

commit;

