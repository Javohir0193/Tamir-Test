revoke all on function public.review_save(bigint, jsonb) from public, anon;
revoke all on function public.admin_reviews(text, text, integer) from public, anon;
revoke all on function public.admin_review_set(text, bigint, text, text) from public, anon;
revoke all on function public.ratings_summary() from public;
