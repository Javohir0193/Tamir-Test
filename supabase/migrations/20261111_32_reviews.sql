-- Ta'mir: дўкон ва товар рейтинги, шарҳлар (ADR-013).
-- Нима учун: харидор дўконни танлашда фақат нархни кўради, сифат ва хизмат ҳақида маълумот йўқ. Бошқа маркетплейслардаги
--   каби баҳо фақат ҳақиқий харидордан бўлиши керак: сохта баҳо (ўз дўконига, буюртмасиз) ишончни йўқотади.
-- Нима ўзгаради (фақат қўшилади):
--   reviews жадвали: битта буюртмада ҳар дўконга битта баҳо (1–5 юлдуз + матн), ҳар товарга битта баҳо (юлдуз, матн ихтиёрий).
--   Қоидалар (review_save ичида, сайтга ишонилмайди):
--     • фақат буюртма эгаси (Telegram орқали кирган профил), буюртма етказилган (pickup: 3, delivery: 4 босқич) ва бекор
--       қилинмаган; етказилгандан кейин app_settings.review_days (одатда 30) кун ичида;
--     • дўкон ва товар шу буюртмада бўлиши шарт (order_lines / purchases); ўз дўконига баҳо қўйиб бўлмайди (own_shop);
--     • матнда ҳавола ёки телефон рақами бўлса — 'pending' (админ кўргунча яширин), акс ҳолда дарҳол 'shown';
--     • админ яширган баҳони харидор қайта ёзса ҳам яширинлигича қолади; соатига 30 тадан ортиқ ёзув — too_fast.
--   Сайт: review_targets(no), review_save(no, items) — authenticated; ratings_summary(), shop_reviews(seller) — очиқ.
--   Админ: admin_reviews(code, status), admin_review_set(code, id, status, reason) — ҳуқуқ 'tickets', аудит журнали.
--   Бот: seller_reviews(seller) — дўкон ўз баҳоларини кўради (фақат service_role).
--   Янги кўринган дўкон баҳоси дўконга Telegram'да хабар қилинади (bot_post dm).
-- Нима ўзгармайди: мавжуд жадваллар, view'лар, функциялар ва уларнинг имзолари; тўлов қисми.
-- Орқага қайтариш: 20261111_32_reviews.down.sql (баҳолар ўчади).
-- Тартиб: 31 дан кейин (мустақил), аввал test базада. SQL Editor'га тўлиқ қўйиб Run.

begin;

create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  order_no    bigint not null references public.orders(no) on delete cascade,
  profile_id  bigint not null references public.profiles(id) on delete cascade,
  seller_id   bigint references public.sellers(id) on delete cascade,
  product_id  integer references public.products(id) on delete cascade,
  rating      smallint not null check (rating between 1 and 5),
  body        text not null default '' check (length(body) <= 1000),
  status      text not null default 'shown' check (status in ('shown', 'pending', 'hidden')),
  hide_reason text,
  decided_by  text,
  decided_at  timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint reviews_one_target check ((seller_id is null) <> (product_id is null))
);
create unique index if not exists reviews_order_seller_uq  on public.reviews (order_no, seller_id)  where seller_id is not null;
create unique index if not exists reviews_order_product_uq on public.reviews (order_no, product_id) where product_id is not null;
create index if not exists reviews_seller_idx  on public.reviews (seller_id, created_at desc)  where status = 'shown';
create index if not exists reviews_product_idx on public.reviews (product_id) where status = 'shown';
create index if not exists reviews_profile_idx on public.reviews (profile_id, updated_at desc);
create index if not exists reviews_pending_idx on public.reviews (created_at) where status = 'pending';

alter table public.reviews enable row level security;
revoke all on table public.reviews from public, anon, authenticated;

insert into public.app_settings (key, value) select 'review_days', '30'
 where not exists (select 1 from public.app_settings where key = 'review_days');

-- буюртма баҳолаш мумкинми: сабаб ('' = мумкин) ва муддат
CREATE OR REPLACE FUNCTION public.review_window(o public.orders)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare ls int := case when o.mode = 'pickup' then 3 else 4 end; done_at timestamptz; till timestamptz;
        days int := coalesce((select nullif(value, '')::int from public.app_settings where key = 'review_days'), 30);
begin
  if o.cancelled_at is not null then return jsonb_build_object('why', 'cancelled'); end if;
  if o.stage < ls then return jsonb_build_object('why', 'not_delivered'); end if;
  done_at := coalesce(o.received_at,
                      case when jsonb_typeof(o.times -> ls) = 'number' then to_timestamp((o.times ->> ls)::bigint / 1000.0) end,
                      o.created_at);
  till := done_at + make_interval(days => days);
  return jsonb_build_object('why', case when till < now() then 'too_late' else '' end, 'until', till);
end $function$;

-- буюртмадаги дўконлар ва товарлар (баҳо қўйиш мумкин бўлганлари)
CREATE OR REPLACE FUNCTION public.review_order_targets(p_no bigint)
 RETURNS TABLE(kind text, id bigint, name text, tg bigint)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select 'shop', s.id, coalesce(nullif(s.shop, ''), s.name), s.tg_chat_id
    from public.sellers s
   where s.role = 'seller'
     and s.id in (select l.seller_id from public.order_lines l where l.order_no = p_no and l.seller_id is not null
                  union select p.shop_id from public.purchases p where p.order_no = p_no)
  union all
  select 'product', p.id, p.name || coalesce(nullif(' ' || p.spec, ' '), ''), null
    from public.products p
   where p.id in (select l.product_id from public.order_lines l where l.order_no = p_no and l.product_id is not null)
$function$;

-- сайт: «Баҳолаш» ойнаси учун маълумот
CREATE OR REPLACE FUNCTION public.review_targets(p_no bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare pid bigint := public.my_profile_id(); o public.orders; w jsonb;
begin
  if pid is null then raise exception 'login_required' using errcode = '42501'; end if;
  select * into o from public.orders where no = p_no and profile_id = pid;
  if not found then raise exception 'not_found'; end if;
  w := public.review_window(o);
  return w || jsonb_build_object('no', p_no,
    'shops', coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'name', t.name, 'rating', r.rating, 'body', r.body, 'status', r.status) order by t.name)
                        from public.review_order_targets(p_no) t left join public.reviews r on r.order_no = p_no and r.seller_id = t.id
                       where t.kind = 'shop'), '[]'::jsonb),
    'products', coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'name', t.name, 'rating', r.rating, 'body', r.body, 'status', r.status) order by t.name)
                        from public.review_order_targets(p_no) t left join public.reviews r on r.order_no = p_no and r.product_id = t.id
                       where t.kind = 'product'), '[]'::jsonb));
end $function$;

-- матнда ҳавола / телефон / @username бор-йўқлиги (бор бўлса админ кўриб чиқади)
CREATE OR REPLACE FUNCTION public.review_needs_check(p_body text)
 RETURNS boolean
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  select coalesce(p_body, '') ~* '(https?://|www\.|t\.me/|telegram\.me|\m[a-z0-9-]+\.(uz|ru|com|org|net|me)\M|(^|\s)@[a-z0-9_]{4,})'
      or regexp_replace(coalesce(p_body, ''), '[\s\-\(\)\.]', '', 'g') ~ '\+?\d{9,}'
$function$;

-- сайт: баҳоларни сақлаш. p_items: [{"kind":"shop"|"product", "id":…, "rating":1-5, "body":"…"}]
CREATE OR REPLACE FUNCTION public.review_save(p_no bigint, p_items jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare pid bigint := public.my_profile_id(); o public.orders; w jsonb; it jsonb; k text; tid bigint; rt int; txt text;
        st text; old public.reviews; t record; me_tg bigint; n int := 0; dms jsonb := '[]'::jsonb; slang text;
begin
  if pid is null then raise exception 'login_required' using errcode = '42501'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then raise exception 'bad_value'; end if;
  select * into o from public.orders where no = p_no and profile_id = pid for update;
  if not found then raise exception 'not_found'; end if;
  w := public.review_window(o);
  if w ->> 'why' <> '' then raise exception '%', w ->> 'why'; end if;
  if (select count(*) from public.reviews where profile_id = pid and updated_at > now() - interval '1 hour') >= 30 then raise exception 'too_fast'; end if;
  select tg_id into me_tg from public.profiles where id = pid;

  for it in select * from jsonb_array_elements(p_items) loop
    k := it ->> 'kind';
    if k not in ('shop', 'product') or jsonb_typeof(it -> 'id') <> 'number' or jsonb_typeof(it -> 'rating') <> 'number' then raise exception 'bad_value'; end if;
    tid := (it ->> 'id')::bigint; rt := (it ->> 'rating')::numeric::int;
    if rt < 1 or rt > 5 or (it ->> 'rating')::numeric <> rt then raise exception 'bad_value'; end if;
    txt := left(btrim(regexp_replace(coalesce(it ->> 'body', ''), '[[:cntrl:]]+', ' ', 'g')), 1000);
    select * into t from public.review_order_targets(p_no) x where x.kind = k and x.id = tid;
    if not found then raise exception 'not_in_order'; end if;
    if k = 'shop' and me_tg is not null and t.tg = me_tg then raise exception 'own_shop'; end if;

    if k = 'shop' then select * into old from public.reviews where order_no = p_no and seller_id = tid;
    else select * into old from public.reviews where order_no = p_no and product_id = tid::int; end if;
    st := case when old.status = 'hidden' then 'hidden' when public.review_needs_check(txt) then 'pending' else 'shown' end;

    if old.id is null then
      insert into public.reviews (order_no, profile_id, seller_id, product_id, rating, body, status)
      values (p_no, pid, case when k = 'shop' then tid end, case when k = 'product' then tid::int end, rt, txt, st);
      if k = 'shop' and st = 'shown' and t.tg is not null then
        select lang into slang from public.sellers where id = tid;
        dms := dms || jsonb_build_array(jsonb_build_object('chat_id', t.tg, 'text',
          case when slang = 'ru' then '⭐ Новая оценка: ' || rt || '/5 · заказ №' || p_no || case when txt <> '' then E'\n«' || left(txt, 300) || '»' else '' end
               else '⭐ Янги баҳо: ' || rt || '/5 · №' || p_no || ' буюртма' || case when txt <> '' then E'\n«' || left(txt, 300) || '»' else '' end end));
      end if;
    elsif old.rating <> rt or old.body <> txt then
      update public.reviews set rating = rt, body = txt, status = st, updated_at = now(),
             decided_by = case when st = 'hidden' then decided_by end, decided_at = case when st = 'hidden' then decided_at end
       where id = old.id;
    end if;
    n := n + 1;
  end loop;
  if jsonb_array_length(dms) > 0 then perform public.bot_post(jsonb_build_object('dm', dms)); end if;
  return jsonb_build_object('ok', true, 'saved', n);
end $function$;

-- очиқ: каталог ва дўкон рўйхати учун ўртача баҳолар {"p": {"id": [ўртача, сони]}, "s": {...}}
CREATE OR REPLACE FUNCTION public.ratings_summary()
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select jsonb_build_object(
    'p', coalesce((select jsonb_object_agg(product_id, jsonb_build_array(a, c)) from
            (select product_id, round(avg(rating), 1) a, count(*) c from public.reviews where status = 'shown' and product_id is not null group by 1) x), '{}'::jsonb),
    's', coalesce((select jsonb_object_agg(seller_id, jsonb_build_array(a, c)) from
            (select seller_id, round(avg(rating), 1) a, count(*) c from public.reviews where status = 'shown' and seller_id is not null group by 1) x), '{}'::jsonb))
$function$;

-- исм: «Javohir Q.» (телефон ва фамилия кўрсатилмайди)
CREATE OR REPLACE FUNCTION public.review_author(p_name text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  select coalesce(nullif(split_part(btrim(coalesce(p_name, '')), ' ', 1), ''), 'Харидор')
      || coalesce(' ' || nullif(left(split_part(btrim(coalesce(p_name, '')), ' ', 2), 1), '') || '.', '')
$function$;

-- очиқ: дўконнинг кўринган баҳолари
CREATE OR REPLACE FUNCTION public.shop_reviews(p_seller bigint, p_limit integer DEFAULT 20)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select jsonb_build_object(
    'avg', (select round(avg(rating), 1) from public.reviews where seller_id = p_seller and status = 'shown'),
    'cnt', (select count(*) from public.reviews where seller_id = p_seller and status = 'shown'),
    'dist', (select jsonb_build_array(count(*) filter (where rating = 1), count(*) filter (where rating = 2), count(*) filter (where rating = 3),
                                      count(*) filter (where rating = 4), count(*) filter (where rating = 5))
               from public.reviews where seller_id = p_seller and status = 'shown'),
    'items', coalesce((select jsonb_agg(jsonb_build_object('r', x.rating, 'body', x.body, 'name', x.nm, 'at', x.created_at) order by x.created_at desc)
                 from (select r.rating, r.body, r.created_at, public.review_author(p.name) nm from public.reviews r join public.profiles p on p.id = r.profile_id
                        where r.seller_id = p_seller and r.status = 'shown' and r.body <> ''
                        order by r.created_at desc limit least(greatest(coalesce(p_limit, 20), 1), 50)) x), '[]'::jsonb))
$function$;

-- бот: дўкон ўз баҳоларини кўради (яширинлари ҳам, сабаби билан эмас)
CREATE OR REPLACE FUNCTION public.seller_reviews(p_seller bigint)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select public.shop_reviews(p_seller, 20)
      || jsonb_build_object('recent', coalesce((select jsonb_agg(jsonb_build_object('no', r.order_no, 'r', r.rating, 'body', r.body, 'at', r.created_at) order by r.created_at desc)
                 from (select * from public.reviews where seller_id = p_seller and status = 'shown' order by created_at desc limit 10) r), '[]'::jsonb))
$function$;

-- модерация (ядро): ҳолат ва сабаб, аудит журнали
CREATE OR REPLACE FUNCTION public.review_moderate(p_id bigint, p_status text, p_reason text, p_by text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r public.reviews; why text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if p_status not in ('shown', 'hidden') then raise exception 'bad_value'; end if;
  if p_status = 'hidden' and length(coalesce(why, '')) < 3 then raise exception 'reason_required'; end if;
  select * into r from public.reviews where id = p_id for update;
  if not found then raise exception 'unknown_key'; end if;
  update public.reviews set status = p_status, hide_reason = case when p_status = 'hidden' then left(why, 300) end,
         decided_by = left(coalesce(p_by, 'admin'), 60), decided_at = now()
   where id = p_id;
  perform public.admin_log('review_' || p_status, 'review', p_id::text, jsonb_build_object('status', r.status),
                           jsonb_build_object('status', p_status), why);
  return jsonb_build_object('ok', true, 'id', p_id, 'status', p_status);
end $function$;

CREATE OR REPLACE FUNCTION public.admin_reviews(p_code text, p_status text DEFAULT NULL::text, p_limit integer DEFAULT 100)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  perform public.admin_check(p_code); perform public.admin_need('tickets');
  return jsonb_build_object(
    'pending', (select count(*) from public.reviews where status = 'pending'),
    'items', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'no', r.order_no, 'r', r.rating, 'body', r.body, 'status', r.status,
               'reason', r.hide_reason, 'at', r.created_at, 'by', p.name, 'phone', p.phone,
               'target', case when r.seller_id is not null then (select '🏪 ' || coalesce(nullif(s.shop, ''), s.name) from public.sellers s where s.id = r.seller_id)
                              else (select '📦 ' || x.name from public.products x where x.id = r.product_id) end) order by r.id desc)
       from (select * from public.reviews where nullif(p_status, '') is null or status = p_status
              order by id desc limit least(greatest(coalesce(p_limit, 100), 1), 500)) r
       join public.profiles p on p.id = r.profile_id), '[]'::jsonb));
end $function$;

CREATE OR REPLACE FUNCTION public.admin_review_set(p_code text, p_id bigint, p_status text, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  perform public.admin_check(p_code); perform public.admin_need('tickets');
  return public.review_moderate(p_id, p_status, p_reason, 'admin:' || coalesce(current_setting('app.admin_name', true), ''));
end $function$;

revoke all on function public.review_window(public.orders) from public, anon, authenticated;
