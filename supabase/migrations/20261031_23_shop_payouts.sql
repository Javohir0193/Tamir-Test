begin;

create table if not exists public.shop_payouts (
  id bigint generated by default as identity primary key,
  seller_id bigint not null references public.sellers(id),
  amount bigint not null check (amount > 0),
  note text,
  admin_id bigint,
  at timestamptz not null default now()
);
alter table public.shop_payouts enable row level security;
create index if not exists shop_payouts_seller_idx on public.shop_payouts (seller_id);

CREATE OR REPLACE FUNCTION public.shop_handed(p_shop bigint)
 RETURNS TABLE(no bigint, total bigint, commission bigint, pct numeric, net bigint, st text)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  with s as (select commission_pct own from public.sellers where id = p_shop),
  cfg as (
    select coalesce((select value::numeric from public.app_settings where key = 'seller_commission_pct'), 0) def,
           coalesce((select value::int from public.app_settings where key = 'commission_free_orders'), 0) freen),
  bought as (select distinct order_no::bigint no from public.purchases where shop_id = p_shop and status in ('pending', 'paid')),
  hl as (
    select l.order_no::bigint no, sum(l.qty * coalesce(l.price, 0))::bigint total
    from public.order_lines l
    where l.seller_id = p_shop and l.loaded and l.status = 'ready'
      and l.order_no::bigint not in (select no from bought)
    group by l.order_no),
  live as (select hl.no, hl.total from hl join public.orders o on o.no = hl.no where o.cancelled_at is null),
  ranked as (select u.no, (row_number() over (order by u.no) - 1) idx from (select no from bought union select no from live) u)
  select x.no, x.total, round(x.total * x.pct / 100)::bigint, x.pct, x.total - round(x.total * x.pct / 100)::bigint, x.st
  from (
    select lv.no, lv.total,
           case when (select own from s) is not null then (select own from s)
                when r.idx < (select freen from cfg) then 0 else (select def from cfg) end pct,
           case when o.stage >= case o.mode when 'pickup' then 3 else 4 end then public.order_payout_state(o) else 'wait' end st
    from live lv join ranked r on r.no = lv.no join public.orders o on o.no = lv.no) x
  order by x.no
$function$;
revoke all on function public.shop_handed(bigint) from public, anon, authenticated;
grant execute on function public.shop_handed(bigint) to service_role;

CREATE OR REPLACE FUNCTION public.admin_shop_queue(p_code text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r jsonb;
begin
  perform public.admin_check(p_code); perform public.admin_need('payout');
  select coalesce(jsonb_agg(q order by (q->>'due')::bigint desc), '[]'::jsonb) into r from (
    select jsonb_build_object('id', s.id, 'name', coalesce(s.shop, s.name), 'phone', s.phone, 'card', s.card,
             'confirmed', h.conf, 'waiting', h.wait, 'held', h.held, 'paid', p.paid, 'due', h.conf - p.paid) q
    from public.sellers s
    cross join lateral (select coalesce(sum(net) filter (where st = 'free'), 0) conf, coalesce(sum(net) filter (where st = 'wait'), 0) wait,
                               coalesce(sum(net) filter (where st = 'hold'), 0) held from public.shop_handed(s.id)) h
    cross join lateral (select coalesce(sum(amount), 0) paid from public.shop_payouts where seller_id = s.id) p
    where s.role = 'seller' and (h.conf <> 0 or h.wait <> 0 or h.held <> 0 or p.paid <> 0)) z;
  return jsonb_build_object('shops', r,
    'recent', coalesce((select jsonb_agg(jsonb_build_object('at', x.at, 'name', coalesce(s.shop, s.name), 'amount', x.amount, 'note', x.note) order by x.id desc)
                        from (select * from public.shop_payouts order by id desc limit 20) x join public.sellers s on s.id = x.seller_id), '[]'::jsonb));
end $function$;

CREATE OR REPLACE FUNCTION public.admin_shop_pay(p_code text, p_seller bigint, p_amount bigint, p_note text DEFAULT NULL::text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare conf bigint; paid bigint; pid bigint; chat bigint;
begin
  perform public.admin_check(p_code); perform public.admin_need('payout');
  if p_amount is null or p_amount <= 0 then raise exception 'bad_amount'; end if;
  perform 1 from public.sellers where id = p_seller and role = 'seller' for update;      -- такрорий босишдан ҳимоя
  if not found then raise exception 'unknown_key'; end if;
  select coalesce(sum(net) filter (where st = 'free'), 0) into conf from public.shop_handed(p_seller);
  select coalesce(sum(amount), 0) into paid from public.shop_payouts where seller_id = p_seller;
  if p_amount > conf - paid then raise exception 'over_balance'; end if;
  insert into public.shop_payouts (seller_id, amount, note, admin_id)
    values (p_seller, p_amount, left(p_note, 200), nullif(current_setting('app.admin_id', true), '')::bigint) returning id into pid;
  perform public.admin_log('shop_pay', 'seller', p_seller::text, jsonb_build_object('due', conf - paid), jsonb_build_object('paid', p_amount), p_note);
  select tg_chat_id into chat from public.sellers where id = p_seller;
  if chat is not null then
    perform public.bot_post(jsonb_build_object('dm', jsonb_build_array(jsonb_build_object('chat_id', chat,
            'text', '💸 Сизга ' || p_amount || ' сўм ўтказилди. Раҳмат!'))));
  end if;
  return pid;
end $function$;

revoke all on function public.admin_shop_queue(text), public.admin_shop_pay(text, bigint, bigint, text) from public, anon;
grant execute on function public.admin_shop_queue(text), public.admin_shop_pay(text, bigint, bigint, text) to authenticated;

commit;
