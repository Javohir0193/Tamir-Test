-- Ta'mir: дўконларга ўтказиш навбати (1-босқич: админ ўтказиб, «ўтказилди» деб белгилайди).
-- Нима ўзгаради:
--   shop_payouts жадвали (дўконга қилинган ўтказмалар);
--   shop_handed(дўкон): товар йиғувчига топширилган буюртмалар — сумма, комиссия, ҳолат (free/wait/hold). Бот ва админ шу функциядан фойдаланади;
--   admin_shop_queue(код): дўконлар рўйхати — ўтказиш керак (тасдиқланган − ўтказилган), кутилмоқда, эътироз, карта;
--   admin_shop_pay(код, дўкон, сумма, изоҳ): ўтказма белгилаш (қолдиқдан ошмайди), дўконга хабар.
-- Нима ўзгармайди: purchases, staff_payouts, мавжуд функциялар.
-- Орқага қайтариш: 20261031_23_shop_payouts.down.sql
